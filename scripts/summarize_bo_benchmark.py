#!/usr/bin/env python3
"""Summarize the deterministic CSV traces emitted by BoBenchmarkTest (standard library only)."""

import argparse
import csv
import statistics
from collections import defaultdict
from pathlib import Path


def summarize(directory):
    traces = defaultdict(dict)
    for path in sorted(directory.glob('*.csv')):
        with path.open() as source:
            for row in csv.DictReader(source):
                key = (row['problem'], row['algorithm'], int(row['seed']))
                step = int(row['evaluations'])
                if step in traces[key]:
                    raise ValueError(f'duplicate result: {key} at {step}')
                traces[key][step] = float(row['simple_regret'])
    if not traces:
        raise ValueError(f'no benchmark traces in {directory}')
    groups = defaultdict(list)
    for (problem, algorithm, seed), steps in traces.items():
        if set(steps) != set(range(1, 33)):
            raise ValueError(f'incomplete 32-evaluation run: {(problem, algorithm, seed)}')
        groups[problem, algorithm].append(steps)
    lines = [
        '# Synthetic BO benchmark results', '',
        'Six seeds (3, 11, 19, 29, 43, 61), 32 evaluations per run, unit evaluation cost, sequential batches.',
        'Values are simple regret at the best **evaluated noiseless reference**, including for noisy observations.',
        'Lower is better. IQR is the inclusive 25th–75th percentile across seeds.', '',
        '| Objective | Algorithm | Median @8 | Median @16 | Median @32 | IQR @32 |',
        '|---|---|---:|---:|---:|---:|',
    ]
    for problem in sorted({key[0] for key in groups}):
        for algorithm in ('local-ei', 'pool-ei', 'legacy-pool-ei', 'random'):
            runs = groups[problem, algorithm]
            if len(runs) != 6:
                raise ValueError(f'expected six seeds: {(problem, algorithm)}')
            medians = [statistics.median(run[step] for run in runs) for step in (8, 16, 32)]
            quartiles = statistics.quantiles([run[32] for run in runs], n=4, method='inclusive')
            values = ' | '.join(f'{value:.6g}' for value in medians)
            lines.append(f'| {problem} | {algorithm} | {values} | {quartiles[0]:.6g}–{quartiles[2]:.6g} |')
    lines += ['', 'Paired final-regret comparisons for `local-ei` (wins / ties / losses):', '',
              '| Objective | Versus normalized pool EI | Versus random search |', '|---|---:|---:|']
    for problem in sorted({key[0] for key in groups}):
        comparisons = []
        for other in ('pool-ei', 'random'):
            wins = ties = losses = 0
            for seed in (3, 11, 19, 29, 43, 61):
                delta = traces[problem, 'local-ei', seed][32] - traces[problem, other, seed][32]
                if abs(delta) <= 1e-12:
                    ties += 1
                elif delta < 0:
                    wins += 1
                else:
                    losses += 1
            comparisons.append(f'{wins} / {ties} / {losses}')
        lines.append(f'| {problem} | {comparisons[0]} | {comparisons[1]} |')
    lines += ['', 'Generated by `python3 scripts/summarize_bo_benchmark.py`; see [methodology](README.md).', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=Path('build/reports/bo-benchmark'))
    parser.add_argument('--output', type=Path)
    arguments = parser.parse_args()
    report = summarize(arguments.input)
    if arguments.output:
        arguments.output.write_text(report)
    else:
        print(report, end='')
